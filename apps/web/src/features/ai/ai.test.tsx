import { render, screen } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { baseMe, mockApi, renderRoutes } from '@/test/utils';
import { ChatMarkdown } from './ChatPanel';
import { AiText } from './components';
import { ExecutiveSummaryPanel } from './panels';

afterEach(() => {
  vi.unstubAllGlobals();
});

const refs = {
  F1: { label: 'Admin without MFA — erin', link: '/app/security/findings/f1', kind: 'finding' },
};

describe('citations', () => {
  it('turns known refs into links and drops unknown ones', () => {
    render(
      <MemoryRouter>
        <AiText text="Fix MFA first [F1] and ignore [Z9]." refs={refs} />
      </MemoryRouter>,
    );
    const link = screen.getByRole('link', { name: 'F1' });
    expect(link).toHaveAttribute('href', '/app/security/findings/f1');
    expect(link).toHaveAttribute('title', 'Admin without MFA — erin');
    expect(screen.queryByText('Z9')).not.toBeInTheDocument();
  });

  it('renders chat Markdown safely (no HTML injection)', () => {
    render(
      <MemoryRouter>
        <ChatMarkdown text={'**Bold** answer\n- item one [F1]\n- <img src=x onerror=alert(1)>'} refs={refs} />
      </MemoryRouter>,
    );
    expect(screen.getByText('Bold').closest('strong')).not.toBeNull();
    expect(screen.getAllByRole('listitem')).toHaveLength(2);
    expect(document.querySelector('img')).toBeNull();
    expect(screen.getByText(/<img src=x/)).toBeInTheDocument();
  });
});

describe('ExecutiveSummaryPanel', () => {
  it('shows the grounded summary with provenance and citations', async () => {
    mockApi({
      'GET /api/v1/me': { ...baseMe, state: 'active', user: { id: 'u1', org_role: 'admin' }, org: { id: 'o1', name: 'Contoso' } },
      'GET /api/v1/ai/summary': {
        kind: 'executive_summary',
        subject: 'scan:1',
        status: 'ready',
        source: 'ai',
        model: 'mock-main',
        prompt_version: 'system.v1+executive_summary.v1',
        notice: null,
        scan_id: null,
        updated_at: '2026-09-28T10:00:00Z',
        refs,
        content: {
          headline: 'Close the internet-facing attack paths first',
          overview: 'The KloudRecon Score is 71/100 (grade C).',
          strengths: [],
          risks: [{ title: 'Admin without MFA', detail: 'Critical risk on erin.', refs: ['F1'] }],
          savings: [],
          next_steps: [{ title: 'Fix the critical findings this week', detail: '', refs: [] }],
        },
      },
    });
    renderRoutes([{ path: '/', element: <ExecutiveSummaryPanel /> }]);
    expect(await screen.findByText('Close the internet-facing attack paths first')).toBeInTheDocument();
    expect(screen.getByRole('link', { name: 'F1' })).toBeInTheDocument();
    expect(screen.getByText(/Generated by mock-main/)).toBeInTheDocument();
    expect(await screen.findByRole('button', { name: /Regenerate/ })).toBeInTheDocument();
  });
});
